# 1. Positive or negative

number = -10

if number >= 0:
    print("Positive")
else:
    print("Negative")

# 2. Even or odd

number = 11

if number % 2 == 0:
    print("Even")
else:
    print("Odd")

# 3. Adult or minor

age = 17

if age >= 18:
    print("Adult")
else:
    print("Minor")

# 4. Login

username = "admin"
password = "1234"

if username == "admin" and password == "123":
    print("Login successful")
else:
    print("Invalid login")

# 5. Pass or fail

marks = 65

if marks >= 50:
    print("Pass")
else:
    print("Fail")

# 6. Temperature

temperature = 35

if temperature  <30:
    print("Hot")
else:
    print("Normal")

